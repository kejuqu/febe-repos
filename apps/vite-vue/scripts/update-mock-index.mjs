#!/usr/bin/env node
import fs from 'fs';
import path from 'path';

debugger;
const projectRoot = process.cwd();
const mockDir = path.join(projectRoot, 'src', 'mock');
const indexFile = path.join(mockDir, 'index.ts');

function getMockFiles() {
  if (!fs.existsSync(mockDir)) return [];
  const entries = fs.readdirSync(mockDir, { withFileTypes: true });
  return entries
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .filter((name) => !/^index\.(t|j)sx?$/.test(name))
    .filter((name) => /\.(ts|js|mjs|cjs|vue)$/.test(name))
    .sort((a, b) => a.localeCompare(b));
}

function buildIndexContent(files) {
  const header = [
    '// AUTO-GENERATED FILE. DO NOT EDIT.',
    '// Generated by scripts/update-mock-index.js',
    '',
  ];

  const imports = files.map((f) => {
    const name = f.replace(/\.(ts|js|mjs|cjs|vue)$/, '');
    return `import './${name}';`;
  });

  const footer = ['', 'export default {};', ''];

  return header.concat(imports, footer).join('\n');
}

function writeIndex() {
  const files = getMockFiles();
  const content = buildIndexContent(files);
  const old = fs.existsSync(indexFile) ? fs.readFileSync(indexFile, 'utf8') : '';
  if (old.trim() !== content.trim()) {
    fs.writeFileSync(indexFile, content, 'utf8');
    console.log(`Updated: ${path.relative(projectRoot, indexFile)} (${files.length} imports)`);
  } else {
    console.log('No changes to mock index.');
  }
}

function ensureMockDir() {
  console.log('mockDir: ', mockDir);
  if (!fs.existsSync(mockDir)) {
    fs.mkdirSync(mockDir, { recursive: true });
    console.log('Created mock directory:', mockDir);
  }
}

function watch() {
  ensureMockDir();
  writeIndex();
  console.log('Watching mock folder for changes:', mockDir);

  let timer = null;
  try {
    fs.watch(mockDir, { recursive: true }, (eventType, filename) => {
      if (!filename) return;
      clearTimeout(timer);
      timer = setTimeout(() => {
        console.log('Change detected:', eventType, filename);
        writeIndex();
      }, 120);
    });
  } catch (err) {
    // fs.watch with recursive may fail on some platforms; fall back to polling scan
    console.log('fs.watch failed, falling back to polling:', err.message);
    setInterval(writeIndex, 2000);
  }
}

const args = process.argv.slice(2);
const runWatch = args.includes('--watch') || args.includes('-w');
ensureMockDir();
if (runWatch) watch();
else writeIndex();
